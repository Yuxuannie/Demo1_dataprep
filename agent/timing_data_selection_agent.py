    async def _query_llm(self, prompt: str) -> str:
        """Query LLM with autonomous prompt."""
        try:
            if hasattr(self.llm, 'invoke'):
                # Try different input formats based on LLM type
                try:
                    # First try direct string input
                    response = self.llm.invoke(prompt)
                except Exception as e1:
                    try:
                        # Try with input key
                        response = self.llm.invoke({"input": prompt})
                    except Exception as e2:
                        # Try as list of messages
                        from langchain.schema import HumanMessage
                        response = self.llm.invoke([HumanMessage(content=prompt)])

                if hasattr(response, 'content'):
                    return response.content
                else:
                    return str(response)
            else:
                return str(self.llm.invoke(prompt))
        except Exception as e:
            print(f"[\033[91mWARNING\033[0m] LLM query failed: {e}")
            return f"ERROR: {e}"

    def _parse_exploration_response(self, response: str) -> Tuple[str, str, str]:
        """Parse agent's autonomous response into thought, action, observation."""
        lines = response.split('\n')
        thought = action = observation = ""

        current_section = None
        for line in lines:
            line = line.strip()
            if line.startswith('THOUGHT:'):
                current_section = 'thought'
                thought += line.replace('THOUGHT:', '').strip() + ' '
            elif line.startswith('ACTION:'):
                current_section = 'action'
                action += line.replace('ACTION:', '').strip() + ' '
            elif line.startswith('OBSERVATION:'):
                current_section = 'observation'
                observation += line.replace('OBSERVATION:', '').strip() + ' '
            elif current_section and line:
                if current_section == 'thought':
                    thought += line + ' '
                elif current_section == 'action':
                    action += line + ' '
                elif current_section == 'observation':
                    observation += line + ' '

        # Generate domain-specific timing analysis thoughts if LLM response is generic
        if not thought or thought in ["Autonomous exploration", "autonomous exploration"]:
            thought = self._generate_timing_specific_thought()

        if not action or action in ["Analyze data patterns", "analyze data patterns"]:
            action = self._generate_timing_specific_action()

        return thought.strip(), action.strip(), observation.strip() or "Timing analysis complete"

